"""Generate OpenAPI and TypeScript schemas from the API; --check detects drift.

Small schema renderer covering this API's OpenAPI subset, not a general-purpose
OpenAPI compiler. Unknown constructs fail instead of silently widening types.
"""
from pathlib import Path
from tempfile import TemporaryDirectory
import json
import sys

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / 'services/api'))
from vela.main import create_app


def ts(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1].replace('-', '_')
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts(s) for s in schema['anyOf'])
    kind = schema.get('type')
    if kind in ('integer', 'number'): return 'number'
    if kind in ('string', 'boolean', 'null'): return kind
    if kind == 'array': return f"({ts(schema['items'])})[]"
    if kind == 'object':
        if 'properties' not in schema: return 'Record<string, unknown>'
        required = schema.get('required', [])
        return '{\n' + '\n'.join(f'  {json.dumps(k)}{"" if k in required else "?"}: {ts(v)};' for k, v in schema['properties'].items()) + '\n}'
    if not schema or set(schema) <= {'title', 'description', 'default'}: return 'unknown'
    raise ValueError(f'Unsupported schema construct: {schema}')


with TemporaryDirectory() as temp:
    app = create_app(f'sqlite:///{Path(temp)/"contract.db"}', 'contract-generation-token-000', local_dir=Path(temp))
    document = app.openapi()
    app.state.store.engine.dispose()

content = '// Generated by scripts/generate-contracts.py. Do not edit.\n'
for name, schema in sorted(document['components']['schemas'].items()):
    content += f'export type {name.replace("-", "_")} = {ts(schema)};\n\n'
outputs = {root/'contracts/openapi.json': json.dumps(document, indent=2, sort_keys=True)+'\n',
           root/'apps/mobile/src/lib/generated.ts': content}
for path, text in outputs.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text(encoding='utf-8') != text:
            raise SystemExit(f'Contract drift: {path.relative_to(root)}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
print('Contract check passed.' if '--check' in sys.argv else 'Generated OpenAPI and TypeScript schemas.')
